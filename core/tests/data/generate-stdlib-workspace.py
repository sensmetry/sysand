"""Generate `stdlib-workspace/` from the published standard-library metadata.

The fixture is derived, never hand-edited: the next OMG release is a new
`stdlib_assets/<date>/` directory and a re-run of this script.

Three things are read rather than assumed:

* the **stems** come from `core/src/stdlib.rs`'s `known_std_libs` table,
  because they are not derivable from the asset filenames --
  `quantities-and-units-library` is `Quantities-and-Units-Domain-Library`;
* the **sources** come from each published `.meta.json`'s `index`, whose
  values are the release's file names, so the fixture can be written
  without the release checked out;
* the **usages** keep their published order, because the comparator
  compares JSON arrays in order.
"""

from __future__ import annotations

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
ASSETS = ROOT / "core/src/stdlib_assets/20250201"
OUT = pathlib.Path(__file__).resolve().parent / "stdlib-workspace"
RELEASE = "20250201"


def stem_table() -> dict[str, tuple[str, str]]:
    """`asset stem -> (stdlib stem, metamodel family)`, from `known_std_libs`."""
    text = (ROOT / "core/src/stdlib.rs").read_text()
    consts = dict(
        re.findall(
            r"const (\w+_INFO_" + RELEASE + r'): &str =\s*include_str!\("([^"]+)"\)',
            text,
        )
    )
    table = {}
    for _iri, family, stem, const in re.findall(
        r'"(https://www\.omg\.org/spec/(\w+)/'
        + RELEASE
        + r'/([^"]+)\.kpar)",\s*(\w+_INFO_'
        + RELEASE
        + r")",
        text,
    ):
        asset = consts[const].split("/")[-1].removesuffix(".project.json")
        table[asset] = (stem, family)
    return table


def toml_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    table = stem_table()
    if len(table) != 10:
        print(f"expected ten libraries, found {len(table)}", file=sys.stderr)
        return 1

    # `<stem>.kpar` -> asset, so a published `resource` usage becomes the
    # `dir` usage of the member it names.
    by_stem = {stem: asset for asset, (stem, _) in table.items()}

    OUT.mkdir(parents=True, exist_ok=True)
    members = sorted(table)
    for asset in members:
        stem, family = table[asset]
        info = json.loads((ASSETS / f"{asset}.project.json").read_text())
        meta = json.loads((ASSETS / f"{asset}.meta.json").read_text())

        lines = [
            "# Generated by `generate-stdlib-workspace.py`; do not edit.",
            "manifest-version = 1",
            "",
            "[project]",
            'publisher = "OMG"',
            f"name = {toml_string(info['name'])}",
            f"version = {toml_string(info['version'])}",
        ]
        if "description" in info:
            # Every published project has one, and it is not a
            # `skip_serializing_if` key, so omitting it would make the
            # built `.project.json` differ from the published one.
            lines.append(f"description = {toml_string(info['description'])}")
        lines += [
            f"stdlib = {toml_string(stem)}",
            f"metamodel.workspace = {toml_string(family.lower())}",
        ]

        sources = sorted(set(meta.get("index", {}).values()))
        if sources:
            lines.append("sources = [")
            lines += [f"  {toml_string(s)}," for s in sources]
            lines.append("]")
        else:
            lines.append("sources = []")

        # Published order, not sorted: JSON arrays compare in order.
        for usage in info.get("usage", []):
            target_stem = usage["resource"].rsplit("/", 1)[-1].removesuffix(".kpar")
            target = by_stem[target_stem]
            target_info = json.loads((ASSETS / f"{target}.project.json").read_text())
            lines += [
                "",
                "[[inline-usages]]",
                'publisher = "OMG"',
                f"name = {toml_string(target_info['name'])}",
                f"dir = {toml_string('../' + target)}",
            ]

        member_dir = OUT / asset
        member_dir.mkdir(exist_ok=True)
        (member_dir / "model.toml").write_text("\n".join(lines) + "\n")

    root = [
        "# Generated by `generate-stdlib-workspace.py`; do not edit.",
        "manifest-version = 1",
        "",
        "[workspace]",
        "members = [",
    ]
    root += [f"  {toml_string(m)}," for m in members]
    root += [
        "]",
        "",
        "# The two metamodel families the release publishes. A member",
        "# inherits one by name; nothing else is shared.",
        "[workspace.group.kerml]",
        f'metamodel = "https://www.omg.org/spec/KerML/{RELEASE}"',
        "",
        "[workspace.group.sysml]",
        f'metamodel = "https://www.omg.org/spec/SysML/{RELEASE}"',
    ]
    (OUT / "model.toml").write_text("\n".join(root) + "\n")
    print(f"wrote {len(members)} members and a root into {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
