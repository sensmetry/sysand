#[test]
/// Legacy json fixture: the setup adds usages with `sysand add`. `sync` itself works on a `model.toml` project.
fn sync_to_current() -> Result<(), Box<dyn std::error::Error>> {
    let (_temp_dir, cwd) = cli_init_json_project(None, "delta", "sync-to-current", "1.2.3", None)?;

    fs::write(cwd.join("test.sysml"), b"package P;\n")?;

    let out = run_sysand_in(&cwd, ["include", "test.sysml"], None)?;

    out.assert().success();

    let out = run_sysand_in(&cwd, ["sync"], None)?;

    out.assert()
        .success()
        .stderr(predicate::str::contains("Creating"))
        .stderr(predicate::str::contains("Syncing"));

    let env_path = cwd.join(DEFAULT_ENV_NAME);

    let env_metadata = fs::read_to_string(env_path.join(METADATA_PATH))?;

    assert_eq!(
        env_metadata,
        r#"# This file is automatically generated by Sysand and is not intended to be edited manually.

version = "0.2"

[[project]]
publisher = "delta"
name = "sync-to-current"
version = "1.2.3"
path = "."
editable = true
"#.to_owned()
    );

    let entries: Result<Vec<_>, _> = fs::read_dir(env_path)?.collect();

    let mut entry_names: Vec<_> = entries?
        .iter()
        .map(|e| e.file_name().to_string_lossy().to_string())
        .collect();

    entry_names.sort();

    assert_eq!(entry_names, [METADATA_PATH]);

    Ok(())
}

#[test]
/// Legacy json fixture: the setup adds usages with `sysand add`. `sync` itself works on a `model.toml` project.
fn repeated_sync_keeps_lockfile_and_env_toml_stable() -> Result<(), Box<dyn std::error::Error>> {
    let (_temp_dir, cwd) = cli_init_json_project(None, "acme", "lock-sync-stable", "1.2.3", None)?;

    let (_dep_temp_dir, dep_cwd) =
        cli_init_json_project(None, "acme", "lock-sync-stable-dep", "2.0.0", None)?;

    let config_path = cwd.join("sysand.toml");
    let cfg = Some(config_path.as_str());

    run_sysand_in(
        &cwd,
        [
            "add",
            "--no-lock",
            "--iri",
            "urn:kpar:lock-sync-stable-dep",
            "--as-editable",
            dep_cwd.as_str(),
        ],
        cfg,
    )?
    .assert()
    .success();

    run_sysand_in(&cwd, ["lock"], cfg)?
        .assert()
        .success()
        .stdout(predicate::str::is_empty());

    let lock_path = cwd.join(DEFAULT_LOCKFILE_NAME);
    let recorded_lockfile = fs::read_to_string(&lock_path)?;

    run_sysand_in(&cwd, ["sync"], cfg)?.assert().success();

    let env_meta_path = cwd.join(DEFAULT_ENV_NAME).join(METADATA_PATH);
    let recorded_env_toml = fs::read_to_string(&env_meta_path)?;

    run_sysand_in(&cwd, ["sync"], cfg)?.assert().success();

    assert_eq!(
        fs::read_to_string(&lock_path)?,
        recorded_lockfile,
        "sysand-lock.toml changed after repeated syncs"
    );
    assert_eq!(
        fs::read_to_string(&env_meta_path)?,
        recorded_env_toml,
        ".sysand/env.toml changed after repeated syncs"
    );

    Ok(())
}

