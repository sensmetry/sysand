/// `sync` with a mix of `LocalSrc` (non-editable) and `Editable` deps in the
/// config must: install the non-editable dep into env, register the editable
/// dep in env.toml without copying it, and also register the current project as
/// editable. Re-running sync is idempotent.
#[test]
/// Legacy json fixture: the setup adds usages with `sysand add`. `sync` itself works on a `model.toml` project.
fn sync_env_toml_with_editable_and_non_editable() -> Result<(), Box<dyn std::error::Error>> {
    // Set up main project with .meta.json (required for sync to lock itself).
    let (_temp_dir, cwd) = cli_init_json_project(None, "acme", "sync-mixed", "1.0.0", None)?;
    fs::write(cwd.join("P.sysml"), "package P;")?;
    run_sysand_in(&cwd, ["include", "P.sysml"], None)?
        .assert()
        .success();

    // Non-editable dep: needs .meta.json so sync can compute its checksum.
    let (_tmp_src, cwd_src) = cli_init_json_project(None, "acme", "sync-mixed-src", "2.0.0", None)?;
    fs::write(cwd_src.join("Q.sysml"), "package Q;")?;
    run_sysand_in(&cwd_src, ["include", "Q.sysml"], None)?
        .assert()
        .success();

    // Editable dep: only .project.json is needed (no install, just reference).
    let (_tmp_editable, cwd_editable) =
        cli_init_json_project(None, "acme", "sync-mixed-editable", "3.0.0", None)?;

    let config_path = cwd.join("sysand.toml");

    // Record sources without re-locking; sync will generate the lockfile.
    run_sysand_in(
        &cwd,
        [
            "add",
            "--no-lock",
            "--iri",
            "urn:kpar:sync-mixed-src",
            "--as-local-src",
            cwd_src.as_str(),
        ],
        Some(config_path.as_str()),
    )?
    .assert()
    .success();

    run_sysand_in(
        &cwd,
        [
            "add",
            "--no-lock",
            "--iri",
            "urn:kpar:sync-mixed-editable",
            "--as-editable",
            cwd_editable.as_str(),
        ],
        Some(config_path.as_str()),
    )?
    .assert()
    .success();

    // First sync: generates lockfile, creates env, installs non-editable dep.
    run_sysand_in(&cwd, ["sync"], Some(config_path.as_str()))?
        .assert()
        .success()
        .stderr(predicate::str::contains(
            "Installing `urn:kpar:sync-mixed-src`",
        ));

    let env_toml = fs::read_to_string(cwd.join(DEFAULT_ENV_NAME).join(METADATA_PATH))?;

    // Non-editable dep is installed with a src checksum.
    assert!(
        env_toml.contains("urn:kpar:sync-mixed-src"),
        "non-editable dep missing from env.toml"
    );
    assert!(
        env_toml.contains("src_cksum"),
        "expected src_cksum for non-editable dep"
    );

    // Editable dep is registered but not installed as a directory copy.
    assert!(
        env_toml.contains("urn:kpar:sync-mixed-editable"),
        "editable dep missing from env.toml"
    );
    assert!(
        env_toml.contains("editable = true"),
        "editable dep should have editable = true"
    );

    // Current project is registered as editable too.
    assert!(
        env_toml.contains("sync-mixed"),
        "current project missing from env.toml"
    );

    // Non-editable dep is physically present inside the env.
    assert!(
        cwd.join(DEFAULT_ENV_NAME)
            .join("lib/kpar.sync-mixed-src_2.0.0")
            .is_dir()
    );

    // Editable dep is NOT copied into the env lib directory.
    assert!(
        !cwd.join(DEFAULT_ENV_NAME)
            .join("lib/kpar.sync-mixed-editable_3.0.0")
            .is_dir()
    );

    // Second sync is idempotent.
    let out = run_sysand_in(&cwd, ["sync"], Some(config_path.as_str()))?;

    out.assert()
        .success()
        .stderr(predicate::str::contains("env is already up to date"));

    Ok(())
}

/// A transitive `kpar_path` usage must resolve relative to the directory of
/// the project that declares it, not relative to the top-level project being
/// synced
#[test]
/// Legacy json fixture: the setup adds usages with `sysand add`. `sync` itself works on a `model.toml` project.
fn sync_kpar_path_usage_transitive() -> Result<(), Box<dyn std::error::Error>> {
    let (_temp_dir, cwd) = cli_init_json_project(None, "acme", "app", "1.2.3", None)?;

    let deps_dir = cwd.join("deps");
    std::fs::create_dir_all(&deps_dir)?;

    // `gadget`: a leaf KPAR, built elsewhere and placed at `deps/gadget.kpar`.
    let gadget_src = cwd.join("gadget_src");
    std::fs::create_dir_all(&gadget_src)?;
    write_legacy_project(&gadget_src, "charlie", "gadget", "2.0.0", None)?;
    run_sysand_in(&gadget_src, ["build", "../deps/gadget.kpar"], None)?
        .assert()
        .success();

    // `widget`: a source directory declaring `../gadget.kpar`, resolved (and
    // stored) relative to `widget`'s own directory.
    let widget_dir = deps_dir.join("widget");
    std::fs::create_dir_all(&widget_dir)?;
    write_legacy_project(&widget_dir, "bravo", "widget", "1.0.0", None)?;
    run_sysand_in(
        &widget_dir,
        ["add", "--no-lock", "--kpar-path", "../gadget.kpar"],
        None,
    )?
    .assert()
    .success();

    run_sysand_in(&cwd, ["add", "--no-lock", "--dir", "deps/widget"], None)?
        .assert()
        .success();

    let out = run_sysand_in(&cwd, ["lock"], None)?;
    out.assert().success();

    let lock_file = Lockfile::read(&cwd)?.into_lock();
    let projects = lock_file.projects;

    assert_eq!(
        projects.len(),
        3,
        "expected app, widget and gadget in the lockfile, got: {projects:#?}"
    );

    // Resolved paths are relativized back against the top-level project
    // root when recorded in the lockfile.
    let widget = projects
        .iter()
        .find(|p| p.name == "widget")
        .unwrap_or_else(|| panic!("`widget` missing from lockfile: {projects:#?}"));
    assert_eq!(widget.version, "1.0.0");
    let [
        Source::LocalSrc {
            src_path,
            checksum: _,
        },
    ] = widget.sources.as_slice()
    else {
        panic!("expected a single local src source for `widget`, got: {widget:#?}");
    };
    assert_eq!(src_path.as_str(), "deps/widget");

    let gadget = projects
        .iter()
        .find(|p| p.name == "gadget")
        .unwrap_or_else(|| panic!("`gadget` missing from lockfile: {projects:#?}"));
    assert_eq!(gadget.version, "2.0.0");
    let [
        Source::LocalKpar {
            kpar_path,
            kpar_size: _,
            kpar_digest: _,
        },
    ] = gadget.sources.as_slice()
    else {
        panic!("expected a single local kpar source for `gadget`, got: {gadget:#?}");
    };
    assert_eq!(kpar_path.as_str(), "deps/gadget.kpar");

    let out = run_sysand_in(&cwd, ["sync"], None)?;
    out.assert().success();

    let env_projects = LocalDirectoryEnvironment::read(cwd.join(DEFAULT_ENV_NAME))?
        .projects()
        .to_vec();

    for (name, version) in [("widget", "1.0.0"), ("gadget", "2.0.0")] {
        assert!(
            env_projects
                .iter()
                .any(|p| p.name == name && p.version == version),
            "`{name}` {version} missing from synced env: {env_projects:#?}"
        );
    }

    Ok(())
}

/// `sync` must remove a project from `.sysand` once it is no longer present
