/// The same, optionally letting the binary discover `sysand.toml`
/// itself.
///
/// Every other helper here appends `--no-config`, and `cfg` is
/// `--config-file`, an explicit path that bypasses discovery. A test of
/// where configuration is *found* must opt in, and accepts that a
/// developer's `$XDG_CONFIG_HOME/sysand/sysand.toml` is then in play.
pub fn sysand_cmd_in_discovering<'a, I: IntoIterator<Item = &'a str>>(
    cwd: &Utf8Path,
    args: I,
    cfg: Option<&'a str>,
    env: &IndexMap<impl AsRef<OsStr>, impl AsRef<OsStr>>,
    discover_config: bool,
) -> Result<Command, Box<dyn Error>> {
    let args = args
        .into_iter()
        .chain((!discover_config).then_some("--no-config"))
        .chain(cfg.iter().flat_map(|cfg| ["--config-file", cfg]));

    // NOTE had trouble getting test-temp-dir crate working, but would be better
    let mut cmd = Command::new(assert_cmd::cargo::cargo_bin!("sysand"));

    // Nothing from the developer's environment reaches the binary unless it
    // is listed here: `SYSAND_*` overrides, `RUST_LOG`, proxies, CI tokens
    // and git's variables would all change what a test sees. Tests that
    // need a variable set it explicitly via `env`, applied last.
    cmd.env_clear();
    for name in [
        // gix runs `git upload-pack` for `file://` git sources
        "PATH",
        "TMPDIR",
        // Windows: temporary files, and networking needs `SystemRoot`
        "TEMP",
        "TMP",
        "SystemRoot",
        // coverage of the spawned binary
        "LLVM_PROFILE_FILE",
    ] {
        if let Some(value) = std::env::var_os(name) {
            cmd.env(name, value);
        }
    }
    cmd.env("NO_COLOR", "1");
    // reqwest also reads the macOS and Windows system proxy settings;
    // `NO_PROXY=*` makes every request go direct regardless.
    cmd.env("NO_PROXY", "*");
    // git reads the user config through `HOME` and `XDG_CONFIG_HOME`, so
    // both point at a directory with no config, and skips the system one.
    let home = concat!(env!("CARGO_TARGET_TMPDIR"), "/empty-home");
    std::fs::create_dir_all(home)?;
    cmd.env("GIT_CONFIG_NOSYSTEM", "1");
    cmd.env("HOME", home);
    cmd.env(
        "XDG_CONFIG_HOME",
        concat!(env!("CARGO_TARGET_TMPDIR"), "/empty-home/.config"),
    );
    // Default the debug-only credential store seam to a simulated-absent
    // keyring so no test ever reads the developer's real OS keyring (which
    // could alter assertions, or pop a keychain prompt on macOS). Tests that
    // need a working store override this via `env`.
    cmd.env("SYSAND_TEST_CREDENTIAL_STORE", ":absent:");
    // A request that fails fails at once, rather than after the retries'
    // waits. Tests of retrying override this via `env`.
    cmd.env("SYSAND_HTTP_RETRIES", "0");
    cmd.envs(env);

    cmd.args(args);

    cmd.current_dir(cwd);

    Ok(cmd)
}

pub fn sysand_cmd_in<'a, I: IntoIterator<Item = &'a str>>(
    cwd: &Utf8Path,
    args: I,
    cfg: Option<&'a str>,
) -> Result<Command, Box<dyn Error>> {
    sysand_cmd_in_with(cwd, args, cfg, &IndexMap::<&str, &str>::default())
}

