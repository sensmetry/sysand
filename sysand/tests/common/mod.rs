/// A checkout of the SysML v2 release, or `None` with a printed notice.
///
/// The release sources are not in this repository, so the suites that
/// need them skip without `SYSAND_STDLIB_SOURCES`. Empty counts as unset,
/// because the CI expression that selects one matrix entry sets the
/// variable to `''` everywhere else.
pub fn stdlib_sources() -> Option<Utf8PathBuf> {
    let root = std::env::var("SYSAND_STDLIB_SOURCES")
        .ok()
        .filter(|value| !value.trim().is_empty());
    if root.is_none() {
        println!(
            "skipping: set SYSAND_STDLIB_SOURCES to a checkout of the \
             SysML v2 release to run the standard-library workspace tests"
        );
    }
    root.map(Utf8PathBuf::from)
}

/// Writes `files` (relative path, content) into `dir`, makes `dir` a git
/// repository and commits them, leaving an index that matches the commit.
///
/// Built with gix in isolation rather than with the `git` binary: no
/// system, user or environment git configuration is read, so nothing on
/// the machine running the tests (commit signing, hooks, a default branch)
/// changes the repository.
pub fn git_commit_files<C: AsRef<[u8]>>(
    dir: &Utf8Path,
    files: &[(&str, C)],
) -> Result<(), Box<dyn Error>> {
    let repo = gix::ThreadSafeRepository::init_opts(
        dir,
        gix::create::Kind::WithWorktree,
        gix::create::Options::default(),
        gix::open::Options::isolated(),
    )?
    .to_thread_local();
    let mut tree = repo.edit_tree(gix::ObjectId::empty_tree(repo.object_hash()))?;
    for (path, content) in files {
        let file = dir.join(path);
        if let Some(parent) = file.parent() {
            std::fs::create_dir_all(parent)?;
        }
        std::fs::write(file, content)?;
        tree.upsert(
            *path,
            gix::object::tree::EntryKind::Blob,
            repo.write_blob(content)?,
        )?;
    }
    let tree = tree.write()?.detach();
    let signature = gix::actor::SignatureRef {
        name: "Test User".into(),
        email: "user@sysand.com".into(),
        time: "0 +0000",
    };
    repo.commit_as(
        signature,
        signature,
        "HEAD",
        "test_commit",
        tree,
        gix::commit::NO_PARENT_IDS,
    )?;
    repo.index_from_tree(&tree)?
        .write(gix::index::write::Options::default())?;
    Ok(())
}

