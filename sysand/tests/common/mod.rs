/// Like [`cli_init_project`], but initializes the project in an already
/// existing `cwd`
pub fn cli_init_project_in(
    cwd: &Utf8Path,
    path: Option<&str>,
    publisher: &str,
    name: Option<&str>,
    version: Option<&str>,
    license: Option<&str>,
) -> Result<Output, Box<dyn Error>> {
    let mut args = vec!["init", "--publisher", publisher, "--metamodel", SYSML];
    if let Some(name) = name {
        args.push("--name");
        args.push(name);
    }
    if let Some(version) = version {
        args.push("--version");
        args.push(version);
    }
    if let Some(license) = license {
        args.push("--license");
        args.push(license);
    }
    if let Some(path) = path {
        args.push(path);
    }
    run_sysand_in(cwd, args, None)
}

/// Install version `version` of a project `publisher`/`name` into the local
/// environment of the project at `root` (creating the environment if
/// missing), as `sync` would. The project's sources are made in a temporary
/// directory, and the environment keeps its own copy.
pub fn install_in_env(
    root: &Utf8Path,
    publisher: &str,
    name: &str,
    version: &str,
) -> Result<(), Box<dyn Error>> {
    install_in_env_with_usage(root, publisher, name, version, &[])
}

/// Like [`install_in_env`], with the project declaring `usage`, each a JSON
/// object of a usage as `.project.json` holds it
pub fn install_in_env_with_usage(
    root: &Utf8Path,
    publisher: &str,
    name: &str,
    version: &str,
    usage: &[&str],
) -> Result<(), Box<dyn Error>> {
    use sysand_core::{
        commands::env::{do_env_install_project, do_env_local_dir},
        env::{DEFAULT_ENV_NAME, local_directory::LocalDirectoryEnvironment},
        project::{ProjectRead as _, local_src::LocalSrcProject, utils::Identifier},
    };

    let (_source_dir, source) = new_temp_cwd()?;
    // A legacy pair, written by hand: the usage is spliced into the
    // `.project.json` below, and `init` writes a `model.toml`
    write_legacy_project(&source, publisher, name, version, None)?;
    if !usage.is_empty() {
        let info_path = source.join(".project.json");
        let info = std::fs::read_to_string(&info_path)?;
        let with_usage = info.replacen(
            &format!(r#""version": "{version}""#),
            &format!(r#""version": "{version}", "usage": [{}]"#, usage.join(", ")),
            1,
        );
        assert_ne!(info, with_usage, "{info}");
        std::fs::write(info_path, with_usage)?;
    }
    let env_path = root.join(DEFAULT_ENV_NAME);
    let mut env = match LocalDirectoryEnvironment::try_read(&env_path)? {
        Some(env) => env,
        None => do_env_local_dir(&env_path)?,
    };
    let project = LocalSrcProject::new_access(source, None);
    do_env_install_project(
        Identifier::from_pub_name(publisher, name).as_str(),
        version,
        &project,
        Some(project.checksum_canonical_variant()?),
        &mut env,
        false,
        true,
    )?;
    Ok(())
}

/// Writes a legacy `.project.json`/`.meta.json` pair by hand.
///
/// Not through the CLI: `sysand init` writes a `model.toml`. Unlike
/// [`cli_init_project`], it returns no process `Output`; nothing runs here.
///
/// The bytes have to match what a real legacy project looks like, not
/// just the field list: `serde_json::to_writer_pretty` plus a trailing
/// newline, camelCase keys, the optional scalars and the empty vectors
/// omitted, and `created` as a whole-second timestamp.
pub fn cli_init_json_project(
    path: Option<&str>,
    publisher: &str,
    name: &str,
    version: &str,
    license: Option<&str>,
) -> Result<(Utf8TempDir, Utf8PathBuf), Box<dyn Error>> {
    let (temp_dir, cwd) = new_temp_cwd()?;
    let project_dir = match path {
        Some(path) => {
            let dir = cwd.join(path);
            std::fs::create_dir_all(&dir)?;
            dir
        }
        None => cwd.clone(),
    };
    write_legacy_project(&project_dir, publisher, name, version, license)?;
    Ok((temp_dir, cwd))
}

/// The legacy pair, for a directory that already exists.
pub fn write_legacy_project(
    dir: &Utf8Path,
    publisher: &str,
    name: &str,
    version: &str,
    license: Option<&str>,
) -> Result<(), Box<dyn Error>> {
    // `license` is a `skip_serializing_if` key, so a fixture that always
    // wrote it, or never did, would not be byte-identical to a real legacy
    // project.
    let mut info = serde_json::Map::new();
    info.insert("name".to_owned(), name.into());
    info.insert("publisher".to_owned(), publisher.into());
    info.insert("version".to_owned(), version.into());
    if let Some(license) = license {
        info.insert("license".to_owned(), license.into());
    }
    let info = serde_json::Value::Object(info);
    // A json project may declare no metamodel, but then it cannot be
    // migrated without `--metamodel`, and most of
    // these fixtures exist to be migrated. A test that is about the
    // missing key writes its own pair.
    let meta = serde_json::json!({
        "index": {},
        "created": format!("{:.0}", jiff::Timestamp::now()),
        "metamodel": SYSML,
    });
    for (file, value) in [(".project.json", &info), (".meta.json", &meta)] {
        let mut text = serde_json::to_string_pretty(value)?;
        text.push('\n');
        std::fs::write(dir.join(file), text)?;
    }
    Ok(())
}

/// A dependency directory with one checksummed model file.
pub fn write_checksummed_dep(dir: &Utf8Path, name: &str) -> Result<(), Box<dyn Error>> {
    std::fs::create_dir_all(dir)?;
    let model = format!("package {name} {{ }}\n");
    std::fs::write(dir.join(format!("{name}.sysml")), &model)?;
    std::fs::write(
        dir.join(".project.json"),
        format!(r#"{{"name":"{name}","publisher":"acme","version":"1.0.0"}}"#),
    )?;
    std::fs::write(
        dir.join(".meta.json"),
        format!(
            r#"{{"index":{{"{name}":"{name}.sysml"}},"created":"2026-01-01T00:00:00Z","checksum":{{"{name}.sysml":{{"algorithm":"SHA256","value":"{}"}}}}}}"#,
            sha256_lowercase_hex(&model)
        ),
    )?;
    Ok(())
}

/// A json app using `dep` (a local source under `deps/dep`), with a
/// lockfile, not yet synced.
pub fn locked_app() -> Result<(Utf8TempDir, Utf8PathBuf), Box<dyn Error>> {
    let (temp_dir, cwd) = new_temp_cwd()?;
    std::fs::write(
        cwd.join(".project.json"),
        r#"{"name":"app","publisher":"acme","version":"0.1.0","description":"an app","usage":[{"resource":"urn:dep","versionConstraint":"^1.0.0"}]}"#,
    )?;
    std::fs::write(cwd.join("app.sysml"), "package app { }\n")?;
    std::fs::write(
        cwd.join(".meta.json"),
        r#"{"index":{"app":"app.sysml"},"created":"2026-01-01T00:00:00Z"}"#,
    )?;
    let dir = cwd.join("deps/dep");
    write_checksummed_dep(&dir, "dep")?;
    let checksum = LocalSrcProject::new_access(&dir, None)
        .checksum_canonical_hex()?
        .expect("manifests");
    let lock = Lock {
        projects: vec![
            Project {
                publisher: Some("acme".to_owned()),
                name: "app".to_owned(),
                version: "0.1.0".to_owned(),
                metamodel: None,
                exports: vec![],
                identifiers: vec![],
                usages: vec![Usage::from_str_unchecked(DEP_IRI)],
                sources: vec![Source::Editable {
                    editable: Utf8UnixPathBuf::from("."),
                }],
            },
            Project {
                publisher: Some("acme".to_owned()),
                name: "dep".to_owned(),
                version: "1.0.0".to_owned(),
                metamodel: None,
                exports: vec![],
                identifiers: vec![DEP_IRI.to_owned()],
                usages: vec![],
                sources: vec![Source::LocalSrc {
                    src_path: Utf8UnixPathBuf::from("deps/dep"),
                    checksum,
                }],
            },
        ],
        ..Lock::default()
    };
    Lockfile::new(&cwd, lock).write()?;
    Ok((temp_dir, cwd))
}

/// A `model.toml` project in `dir`, which must exist: publisher `acme`
/// and the given `name` and `version`, followed by `body` (`sources`,
/// `metamodel`, usages, ...), which is written as is.
pub fn write_toml_project(
    dir: impl AsRef<Utf8Path>,
    name: &str,
    version: &str,
    body: &str,
) -> Result<(), Box<dyn Error>> {
    std::fs::write(
        dir.as_ref().join("model.toml"),
        format!(
            "manifest-version = \"1.0\"\n\n[project]\npublisher = \"acme\"\nname = \"{name}\"\n\
             version = \"{version}\"\n{body}"
        ),
    )?;
    Ok(())
}

/// A Syside json project in `dir` (the extracted form of a Syside
/// archive), which is created: publisher `acme`, the given `name` and
/// `version`, `usage` as its `.project.json` usages, and `files` written
/// and checksummed. The first file is `root`, and `exports` is written as
/// given. A Syside `model.toml` names `root` alone and cannot be built,
/// so a Syside archive is built from this form.
pub fn write_syside_json_project(
    dir: impl AsRef<Utf8Path>,
    name: &str,
    version: &str,
    usage: serde_json::Value,
    exports: &[&str],
    files: &[(&str, &[u8])],
) -> Result<(), Box<dyn Error>> {
    let dir = dir.as_ref();
    std::fs::create_dir_all(dir)?;
    let mut checksum = serde_json::Map::new();
    for (path, contents) in files {
        let file = dir.join(path);
        if let Some(parent) = file.parent() {
            std::fs::create_dir_all(parent)?;
        }
        std::fs::write(file, contents)?;
        checksum.insert(
            (*path).to_owned(),
            serde_json::json!({
                "value": sha256_lowercase_hex(contents),
                "algorithm": "SHA256",
            }),
        );
    }
    std::fs::write(
        dir.join(".project.json"),
        serde_json::json!({
            "name": name,
            "publisher": "acme",
            "version": version,
            "usage": usage,
        })
        .to_string(),
    )?;
    std::fs::write(
        dir.join(".meta.json"),
        serde_json::json!({
            "root": files[0].0,
            "exports": exports,
            "created": "2026-01-01T00:00:00.000000000Z",
            "metamodel": "https://www.sysand.com/spec/SysML/20250201",
            "checksum": checksum,
        })
        .to_string(),
    )?;
    Ok(())
}

/// A `model.toml` workspace root in `dir`, which must exist, listing
/// `members`, followed by `extra` (more `[workspace]` keys), which is
/// written as is.
pub fn write_workspace_root(
    dir: impl AsRef<Utf8Path>,
    members: &[&str],
    extra: &str,
) -> Result<(), Box<dyn Error>> {
    let members: Vec<String> = members.iter().map(|m| format!("\"{m}\"")).collect();
    std::fs::write(
        dir.as_ref().join("model.toml"),
        format!(
            "manifest-version = \"1.0\"\n\n[workspace]\nmembers = [{}]\n{extra}",
            members.join(", ")
        ),
    )?;
    Ok(())
}

/// The bytes of a stored zip archive holding `entries`, as `(name, content)`.
pub fn kpar_bytes(entries: &[(&str, &[u8])]) -> Vec<u8> {
    use std::io::Write as _;

    let mut buf: Vec<u8> = Vec::new();
    {
        let mut zip = zip::ZipWriter::new(std::io::Cursor::new(&mut buf));
        let options = zip::write::SimpleFileOptions::default()
            .compression_method(zip::CompressionMethod::Stored)
            .unix_permissions(0o755);
        for (name, content) in entries {
            zip.start_file(*name, options).unwrap();
            zip.write_all(content).unwrap();
        }
        zip.finish().unwrap();
    }
    buf
}

/// A minimal `.kpar` at `path`: the two manifests at the archive root.
pub fn write_kpar(
    path: &Utf8Path,
    project_json: &str,
    meta_json: &str,
) -> Result<(), Box<dyn Error>> {
    std::fs::write(
        path,
        kpar_bytes(&[
            (".project.json", project_json.as_bytes()),
            (".meta.json", meta_json.as_bytes()),
        ]),
    )?;
    Ok(())
}

/// Creates a temporary directory and returns the tuple of the temporary
