def test_end_to_end_install_sources() -> None:
    # A standard library is identified by its hard-coded IRI; the version must
    # match the embedded standard library metadata so that every `Dependencies`
    # mode resolves the same usage.
    std_iri = "https://www.omg.org/spec/KerML/20250201/Function-Library.kpar"
    std_version = "1.0.0"

    with (
        tempfile.TemporaryDirectory() as tmp_main,
        tempfile.TemporaryDirectory() as tmp_dep,
        tempfile.TemporaryDirectory() as tmp_std,
    ):
        tmp_main = Path(tmp_main).resolve()
        tmp_dep = Path(tmp_dep).resolve()
        tmp_std = Path(tmp_std).resolve()
        sysand.init(
            project_dir=tmp_main,
            name="test_end_to_end_install_sources",
            publisher="a",
            version="1.2.3",
        )
        sysand.init(
            project_dir=tmp_dep,
            name="test_end_to_end_install_sources_dep",
            publisher="a",
            version="1.2.3",
        )
        sysand.init(
            project_dir=tmp_std,
            name="Kernel Function Library",
            publisher="a",
            version=std_version,
        )

        with open(Path(tmp_main) / "src.sysml", "w") as f:
            f.write("package Src;")

        sysand.include(project_dir=tmp_main, src_path="src.sysml")

        with open(Path(tmp_dep) / "src_dep.sysml", "w") as f:
            f.write("package SrcDep;")

        sysand.include(project_dir=tmp_dep, src_path="src_dep.sysml")

        with open(Path(tmp_std) / "src_std.sysml", "w") as f:
            f.write("package SrcStd;")

        sysand.include(project_dir=tmp_std, src_path="src_std.sysml")

        env_path = Path(tmp_main) / sysand.env.DEFAULT_ENV_NAME

        sysand.env.env(path=env_path)

        sysand.env.install_path(
            env_path=env_path,
            iri="urn:kpar:test_end_to_end_install_sources_dep",
            location=tmp_dep,
        )
        sysand.env.install_path(env_path=env_path, iri=std_iri, location=tmp_std)

        sysand.add(
            project_dir=tmp_main,
            iri="urn:kpar:test_end_to_end_install_sources_dep",
            version_constraint="1.2.3",
            lock=False,
        )
        sysand.add(
            project_dir=tmp_main,
            iri=std_iri,
            version_constraint=std_version,
            lock=False,
        )

        dep_src = (
            env_path
            / "lib"
            / "kpar.test_end_to_end_install_sources_dep_1.2.3"
            / "src_dep.sysml"
        )

        [std_src] = (env_path / "lib").glob("*/src_std.sysml")

        # By default, as in the CLI, the project's own sources are listed with
        # those of its dependencies other than std libs, from the project's
        # own environment.
        compare_sources(
            sysand.sources(project_dir=tmp_main),
            [str(Path(tmp_main) / "src.sysml"), str(dep_src)],
        )
        # A project with no environment and no dependencies lists its own.
        compare_sources(
            sysand.sources(project_dir=tmp_dep),
            [str(Path(tmp_dep) / "src_dep.sysml")],
        )
        # Only the project's own sources.
        compare_sources(
            sysand.sources(project_dir=tmp_main, dependencies=sysand.Dependencies.NONE),
            [str(Path(tmp_main) / "src.sysml")],
        )
        # Own sources together with dependency sources, excluding std libs.
        compare_sources(
            sysand.sources(
                project_dir=tmp_main,
                dependencies=sysand.Dependencies.DEPS,
                env_path=env_path,
            ),
            [str(Path(tmp_main) / "src.sysml"), str(dep_src)],
        )
        # Only dependency sources.
        compare_sources(
            sysand.sources(
                project_dir=tmp_main,
                include_own=False,
                dependencies=sysand.Dependencies.DEPS,
                env_path=env_path,
            ),
            [str(dep_src)],
        )
        # Neither own sources nor dependencies yields nothing.
        compare_sources(
            sysand.sources(
                project_dir=tmp_main,
                include_own=False,
                dependencies=sysand.Dependencies.NONE,
            ),
            [],
        )

        # DEPS_STD includes both the dependency and the std lib.
        compare_sources(
            sorted(
                sysand.sources(
                    project_dir=tmp_main,
                    include_own=False,
                    dependencies=sysand.Dependencies.DEPS_STD,
                    env_path=env_path,
                ),
                key=lambda p: Path(p).name,
            ),
            sorted([str(dep_src), str(std_src)], key=lambda p: Path(p).name),
        )
        # STD includes only the std lib.
        compare_sources(
            sysand.sources(
                project_dir=tmp_main,
                include_own=False,
                dependencies=sysand.Dependencies.STD,
                env_path=env_path,
            ),
            [str(std_src)],
        )

        sysand.exclude(project_dir=tmp_main, src_path="src.sysml")

        compare_sources(
            sysand.sources(
                project_dir=tmp_main,
                dependencies=sysand.Dependencies.DEPS,
                env_path=env_path,
            ),
            [str(dep_src)],
        )
        compare_sources(
            sysand.sources(
                project_dir=tmp_main,
                include_own=False,
                dependencies=sysand.Dependencies.DEPS,
                env_path=env_path,
            ),
            [str(dep_src)],
        )


def test_root() -> None:
    with tempfile.TemporaryDirectory() as tmpdirname:
        tmpdirname = Path(tmpdirname).resolve()
        sysand.init(
            project_dir=tmpdirname, name="test_root", publisher="a", version="1.2.3"
        )

        subdir = tmpdirname / "sub" / "nested"
        subdir.mkdir(parents=True)

        root_from_top = sysand.root(path=tmpdirname)
        root_from_sub = sysand.root(path=subdir)

        assert root_from_top is not None
        assert root_from_sub is not None
        assert os.path.samefile(root_from_top, tmpdirname)
        assert os.path.samefile(root_from_sub, tmpdirname)


